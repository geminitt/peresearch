"""The data filter: whether a plain-text file holds data rather than something to read, and what kind.

A data file (a log, a table, a word list, JSON, labels, tokens and tags, lists of addresses or numbers) is kept out
of ranking: its chunks would crowd out the notes and papers a question needs (KITTI tracking labels came to 7,881
chunks against 7,098 for everything else, 2026-10-03). It is not lost: the tools still read and grep it, and
`Index.why_not` says why it is not searched by meaning.

Every test is language-independent: Unicode categories, line shapes and punctuation, no word lists, so it holds for
the six target languages. A file is judged on up to SAMPLE lines taken from its start, middle and end; one under
MIN_LINES lines is too short for line statistics and is left out only when it is mostly numbers (3 lines and 40
characters at least: KITTI's 7-line calibration files). Only plain text is judged: Markdown and code are
written to be read, BibTeX and LaTeX are structured but worth reading. Code is left out only when a tool wrote it
(a generator's note such as "DO NOT EDIT" or "@generated" in its first lines; a mutation-testing copy, whose
functions are each there many times under names like f__mutmut_3) or packed it (minified: lines of more than 500
characters on average; a file of a few very long lines is caught by the same mean). A SQL file is data
when most of its lines are table rows (a dump); a schema or a migration is read. For plain text, the features, in the order they decide:

- URLs or numbers alone: ≥ 90% of the lines are a single URL or numbers (the first rule, kept: lists of addresses);
- JSON: ≥ 60% of the lines start like a JSON record ({ } [ ] ");
- table: ≥ 60% of the lines are rows: the same number (≥ 1) of the same delimiter (, tab ; |) and no cell of
  more than four words (prose between commas is longer);
- numbers and codes: letters (and the marks of scripts such as Devanagari) are < 50% of the characters;
- log: ≥ 50% of the lines start with the same stamp (a start shape with two or more number groups), or ≥ 70% start
  with a long number or a date or time — a numbered list ("1.", "2)") is neither;
- word list: < 30% of the characters stand in lines of six or more words (a CJK character counts as half a word).

Measured on a labelled public set (eval/datafilter.py: 263 files, prose in six languages against logs, tables, word
lists, tokens, labels, JSON): data caught 121 of 121, prose kept 141 of 142 (an AUTHORS.rst, a list of names, called a word list) — in sample:
the thresholds were chosen on that set, with room left on each side of the prose it holds.
"""

import re
import unicodedata
from collections import Counter

from peresearch.zetokrag.parse import CODE

VERSION = 3                  # raise when a rule changes: the index judges plain text and code again
                             # (2: SQL dumps, 2026-10-04; 3: mutation-testing copies, 2026-10-05)
SAMPLE = 600
MIN_LINES = 20
JUDGED = {".txt", ".rst", ".org"}              # plain text; .bib and .tex are read, Markdown and code too
MARKUP = {".html", ".htm"}                     # judged as code when read as it is (a page's main text is not)
_CJK = re.compile(r"[぀-ヿ㐀-鿿가-힯豈-﫿]")
_URL_LINE = re.compile(r"^\S+://\S+$")
_NUMBER_LINE = re.compile(r"^[-+.,:;/|eE\d\s]*\d[-+.,:;/|eE\d\s]*$")
_STAMP_LED = re.compile(r"^(\d{3,}|\d{1,4}[-/.:]\d{1,2}[-/.:]\d{1,4})")
# What code generators write at the top of a file (after GitHub Linguist's rules): "DO NOT EDIT" in capitals, as
# tools write it ("Do not edit the config by hand" is a person's comment), and the usual generator notes.
_GENERATED = re.compile(r"DO NOT EDIT|(?i:@generated\b|code generated by|auto-?generated (file|code)|"
                        r"this file (is|was) (automatically )?generated|generated by the protocol buffer compiler)")
HEADER_LINES = 10
# mutmut's copy of a project (its mutants/ folder): every function many times over, renamed f__mutmut_orig,
# f__mutmut_1, … beside its trampoline, which is imported after the module's docstring, past any header
# (nanovitok/mutants/: 18,284 of its 19,344 chunks, 2026-10-05). Nobody names functions so by hand; two
# definitions can be a person's own test of mutmut, three are its copies.
_MUTANT = re.compile(r"^[ \t]*(?:async[ \t]+)?def[ \t]+\w+__mutmut_\d+[ \t]*\(", re.MULTILINE)
MUTANT_COPIES = 3
# A SQL dump's rows: every line of an INSERT statement (from INSERT INTO to the ";" that ends it: one row a line,
# value tuples a line each, or one statement over several lines) and the rows of a COPY … FROM stdin block
_SQL_INSERT = re.compile(r"^INSERT\s+INTO\b", re.IGNORECASE)
SQL_ROWS = 0.6
MINIFIED_MEAN = 500          # characters per line on average: written code stays far below


def _sample(lines: list[str]) -> list[str]:
    if len(lines) <= SAMPLE:
        return lines
    third, mid = SAMPLE // 3, len(lines) // 2
    return lines[:third] + lines[mid - third // 2:mid + third // 2] + lines[-third:]


def _words(line: str) -> float:
    """Words of a line: pieces between spaces that hold a letter, a CJK character counting as half a word."""
    rest = _CJK.sub(" ", line)
    return len(_CJK.findall(line)) / 2 + sum(any(c.isalpha() for c in w) for w in rest.split())


def _shape(text: str) -> str:
    return re.sub(r"(.)\1+", r"\1", re.sub(r"\d", "9", re.sub(r"[^\W\d_]", "a", text)))


def features(text: str) -> dict:
    """The measurements every judgement rests on (see the module's docstring)."""
    lines = _sample([x.strip() for x in text.split("\n") if x.strip()])
    chars = [c for x in lines for c in x if not c.isspace()]
    if not chars:
        return {"lines": 0, "letters": 0.0, "long": 0.0, "stamps": 0.0, "fields": 0.0, "json": 0.0,
                "digit_led": 0.0, "addresses": 0.0}
    n, total = len(lines), sum(len(x) for x in lines)
    start, count = Counter(_shape(x[:16]) for x in lines).most_common(1)[0]
    fields = 0.0
    for d in ",\t;|":
        k = Counter(x.count(d) for x in lines).most_common(1)[0][0]
        if k >= 1:                     # a row: that many delimiters, and short cells (prose between commas is long)
            rows = sum(x.count(d) == k and max(_words(cell) for cell in x.split(d)) <= 4 for x in lines)
            fields = max(fields, rows / n)
    return {
        "lines": n,
        "letters": sum(unicodedata.category(c)[0] in "LM" for c in chars) / len(chars),
        "long": sum(len(x) for x in lines if _words(x) >= 6) / total,
        "stamps": count / n if len(re.findall(r"9+", start)) >= 2 else 0.0,
        "fields": fields,
        "json": sum(x[0] in '{}[]"' for x in lines) / n,
        "digit_led": sum(bool(_STAMP_LED.match(x)) for x in lines) / n,
        "addresses": sum(bool(_URL_LINE.match(x) or _NUMBER_LINE.match(x)) for x in lines) / n,
    }


def judges(name: str) -> bool:
    """Whether the filter has a say on a file of this name (plain text or code)."""
    dot = name.rfind(".")
    return dot != -1 and (name[dot:].lower() in JUDGED or name[dot:].lower() in CODE | MARKUP)


def reason(name: str, text: str) -> str | None:
    """What kind of data the file `name` holding `text` is, or None when it is something to read."""
    dot = name.rfind(".")
    ext = name[dot:].lower() if dot != -1 else ""
    if ext in CODE | MARKUP:
        return _code(text) or (_sql(text) if ext == ".sql" else None)
    if ext not in JUDGED:
        return None
    f = features(text)
    if f["lines"] < MIN_LINES:            # too short for line statistics; mostly numbers is clear even so
        small = f["lines"] >= 3 and len(text.strip()) >= 40 and f["letters"] < 0.5
        return "numbers and codes" if small else None
    for why, hit in (("URLs or numbers alone", f["addresses"] >= 0.9), ("JSON", f["json"] >= 0.6),
                     ("table", f["fields"] >= 0.6), ("numbers and codes", f["letters"] < 0.5),
                     ("log", f["stamps"] >= 0.5 or f["digit_led"] >= 0.7), ("word list", f["long"] < 0.3)):
        if hit:
            return why
    return None


def _sql(text: str) -> str | None:
    """"SQL data" when at least SQL_ROWS of the non-blank lines are table rows: lines of INSERT statements or of a COPY
    … FROM stdin block; a schema or a migration seeding a few rows is read."""
    rows, n, inside, copying = 0, 0, False, False
    for line in text.split("\n"):
        line = line.strip()
        if not line:
            continue
        n += 1
        if copying:
            copying = line != "\\."
            rows += copying
        elif inside or _SQL_INSERT.match(line):
            rows += 1
            inside = not line.endswith(";")
        elif line.upper().startswith("COPY ") and line.upper().endswith("FROM STDIN;"):
            copying = True
    return "SQL data" if n and rows / n >= SQL_ROWS else None


def _code(text: str) -> str | None:
    """Code a tool wrote (a generator's note in the first lines) or packed (minified), else None."""
    lines = text.split("\n")
    if _GENERATED.search("\n".join(lines[:HEADER_LINES])):
        return "generated code"
    copies = _MUTANT.finditer(text)
    if sum(1 for _ in zip(range(MUTANT_COPIES), copies)) == MUTANT_COPIES:
        return "mutation-testing copy"
    lengths = [len(x) for x in lines if x.strip()]
    # (a second rule, "five lines or fewer, one over 5,000 characters", never decided: such a file's mean is over
    # 1,000 — found by its surviving mutants, 2026-10-04, and removed)
    if lengths and sum(lengths) / len(lengths) > MINIFIED_MEAN:
        return "minified code"
    return None
